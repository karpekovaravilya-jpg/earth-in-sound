@app.route("/sonify", methods=["POST"])
def sonify():
    try:
        data = request.json

        video_url = data.get("videoUrl")
        settings = data.get("audioSettings", {})

        if not video_url:
            return jsonify({"error": "Missing videoUrl"}), 400

        # Загружаем NASA-видео
        response = requests.get(video_url, timeout=120)
        response.raise_for_status()

        with tempfile.NamedTemporaryFile(
            suffix=".mp4", delete=False
        ) as temp:
            temp.write(response.content)
            video_path = temp.name

        try:
            # Используем существующий алгоритм
            video_data = analyze_video(video_path)
            music_data = create_music_data(video_data)

            notes = music_data["notes"]
            durations = music_data["durations"]
            volumes = music_data["volumes"]

            min_midi = settings.get("pitchRange", {}).get("minMidi", 48)
            max_midi = settings.get("pitchRange", {}).get("maxMidi", 84)

            tempo = float(settings.get("tempo", 120))
            speed = tempo / 120 if tempo > 10 else tempo

            events = []
            current_time = 0

            for note, duration, volume in zip(
                notes, durations, volumes
            ):
                midi = int(round(
                    69 + 12 * np.log2(float(note) / 440)
                ))

                midi = int(np.clip(midi, min_midi, max_midi))

                events.append({
                    "time": current_time,
                    "duration": float(duration) / speed,
                    "midi": midi,
                    "velocity": float(volume)
                })

                current_time += 1.0 / speed

            return jsonify({"events": events})

        finally:
            os.remove(video_path)

    except Exception as e:
        return jsonify({"error": str(e)}), 500


