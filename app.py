import numpy as np

def generate_audio(
    music_data,
    filename="music.wav",
    instrument="piano",
    sample_rate=44100
):
    # Доступные инструменты
    instruments = ["piano", "synth", "strings", "bell"]

    if instrument not in instruments:
        raise ValueError(
            f"Неизвестный инструмент. Выбери один из: {instruments}"
        )

    audio = []

    # Получаем музыкальные данные
    notes = music_data["notes"]
    durations = music_data["durations"]
    volumes = music_data["volumes"]

    # Проверяем, что данные не пустые
    if len(notes) == 0:
        raise ValueError("Нет музыкальных данных для генерации.")

    # Генерируем каждую ноту
    for note, duration, volume in zip(notes, durations, volumes):

        t = np.linspace(
            0,
            duration,
            int(sample_rate * duration),
            endpoint=False
        )

        # Основная частота
        fundamental = np.sin(2 * np.pi * note * t)

        # Выбираем тембр инструмента
        if instrument == "piano":
            wave = (
                0.55 * fundamental +
                0.30 * np.sin(2 * np.pi * note * 2 * t) +
                0.15 * np.sin(2 * np.pi * note * 3 * t)
            )
            envelope = np.exp(-5 * t / duration)

        elif instrument == "synth":
            wave = (
                0.65 * fundamental +
                0.25 * np.sin(2 * np.pi * note * 2 * t) +
                0.10 * np.sin(2 * np.pi * note * 3 * t)
            )
            envelope = np.ones(len(t))

        elif instrument == "strings":
            wave = (
                0.70 * fundamental +
                0.20 * np.sin(2 * np.pi * note * 2 * t) +
                0.10 * np.sin(2 * np.pi * note * 3 * t)
            )
            envelope = np.linspace(0.3, 1.0, len(t))

        elif instrument == "bell":
            wave = (
                0.65 * fundamental +
                0.25 * np.sin(2 * np.pi * note * 2.4 * t) +
                0.10 * np.sin(2 * np.pi * note * 4.1 * t)
            )
            envelope = np.exp(-7 * t / duration)

        # Применяем громкость и огибающую
        sound = volume * wave * envelope

        audio.extend(sound)

    # Преобразуем звук в массив
    audio = np.array(audio)

    # Нормализуем громкость
    max_amplitude = np.max(np.abs(audio))

    if max_amplitude > 0:
        audio = audio / max_amplitude

    audio = (audio * 32767).astype(np.int16)

    # Сохраняем WAV-файл
    write(filename, sample_rate, audio)

    return filename

