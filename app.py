def analyze_video(video_path, sample_interval=1):
    cap = cv2.VideoCapture(video_path)

    fps = cap.get(cv2.CAP_PROP_FPS)
    step = max(1, round(fps * sample_interval))

    brightness = []
    colors = []
    changes = []

    previous_frame = None
    frame_number = 0

    while True:
        ret, frame = cap.read()

        if not ret:
            break

        if frame_number % step == 0:
            gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)

            brightness.append(np.mean(gray))
            colors.append(cv2.mean(frame)[:3])

            if previous_frame is not None:
                difference = cv2.absdiff(gray, previous_frame)
                changes.append(np.mean(difference))

            previous_frame = gray

        frame_number += 1

    cap.release()

    return {
        "brightness": np.array(brightness),
        "colors": np.array(colors),
        "changes": np.array(changes)
    }

import numpy as np

# Пентатоническая гамма: C, D, E, G, A
scale = np.array([261.63, 293.66, 329.63, 392.00, 440.00])

def brightness_to_notes(brightness):
    normalized = (brightness - brightness.min()) / (
        brightness.max() - brightness.min() + 1e-9
    )

    indexes = np.round(normalized * (len(scale) - 1)).astype(int)

    return scale[indexes]

def changes_to_rhythm(changes):
    normalized = (changes - changes.min()) / (
        changes.max() - changes.min() + 1e-9
    )

    # Чем сильнее изменения, тем быстрее сменяются ноты
    durations = 0.8 - normalized * 0.5

    return durations


def changes_to_volume(changes):
    normalized = (changes - changes.min()) / (
        changes.max() - changes.min() + 1e-9
    )

    return 0.2 + normalized * 0.6

def create_music_data(video_data):
    notes = brightness_to_notes(video_data["brightness"])
    durations = changes_to_rhythm(video_data["changes"])
    volumes = changes_to_volume(video_data["changes"])

    # Выравниваем длину последовательностей
    length = min(len(notes), len(durations), len(volumes))

    return {
        "notes": notes[:length],
        "durations": durations[:length],
        "volumes": volumes[:length]
    }

